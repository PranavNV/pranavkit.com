/* ---------- Google Scholar merge ----------
   js/scholar.js is regenerated by tools/update_scholar.py. Papers it lists that
   are missing from data.js are added with a guessed domain. Per-paper citation
   counts are not shown; the home-page totals only appear while the snapshot is
   younger than FRESH_DAYS. */
const FRESH_DAYS = 45;
const SCH = typeof SCHOLAR_DATA !== "undefined" && (Date.now() - Date.parse(SCHOLAR_DATA.updated)) / 864e5 <= FRESH_DAYS ? SCHOLAR_DATA : null;

function guessDomains(t) {
  const rules = [["P", /persona|simulat|companion|personality/i], ["D", /deep research|autoresearch|scientific idea|search|answer engine|retriev/i],
    ["C", /persua|agent-to-agent|multi-agent|agent network|belief/i], ["A", /agent|judge|pipeline|benchmark/i],
    ["H", /privacy|police|policy|moderation|governance|social scien|human/i], ["T", /bias|fair|harm|safety|trust|ethic|stereotyp/i]];
  const d = rules.filter(([, re]) => re.test(t)).map(([k]) => k);
  return d.length ? d.slice(0, 2) : ["T"];
}

(function mergeScholar() {
  if (typeof SCHOLAR_DATA === "undefined") return;
  const norm = (t) => t.toLowerCase().replace(/[^a-z0-9]+/g, "").slice(0, 48);
  const byTitle = new Map(PUBLICATIONS.map((p) => [norm(p.t), p]));
  for (const s of SCHOLAR_DATA.papers) {
    const p = byTitle.get(norm(s.t));
    if (p) continue;
    PUBLICATIONS.unshift({ y: s.y || new Date().getFullYear(), t: s.t, a: s.a, v: s.v || "Google Scholar", vs: (s.v || "Paper").split(/[(,]/)[0].trim(), u: s.u, d: guessDomains(s.t) });
  }
  PUBLICATIONS.sort((a, b) => b.y - a.y);
})();

