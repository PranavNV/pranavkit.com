/* ---------- Motion ---------- */
function motion() {
  const io = new IntersectionObserver((ents) => {
    for (const e of ents) if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); }
  }, { threshold: 0.12 });
  $$(".reveal, .stagger").forEach((n) => io.observe(n));

  // count-up numbers
  const co = new IntersectionObserver((ents) => {
    for (const e of ents) {
      if (!e.isIntersecting) continue;
      co.unobserve(e.target);
      const end = +e.target.dataset.count, t0 = performance.now(), dur = 1600;
      if (matchMedia("(prefers-reduced-motion: reduce)").matches) { e.target.textContent = end.toLocaleString(); continue; }
      const step = (t) => {
        const k = Math.min(1, (t - t0) / dur);
        e.target.textContent = Math.round(end * (1 - Math.pow(1 - k, 4))).toLocaleString();
        if (k < 1) requestAnimationFrame(step);
      };
      requestAnimationFrame(step);
    }
  });
  $$("[data-count]").forEach((n) => co.observe(n));

  if (!matchMedia("(pointer: fine)").matches) return;
  // magnetic buttons
  $$(".btn").forEach((b) => {
    b.addEventListener("pointermove", (e) => {
      const r = b.getBoundingClientRect();
      b.style.transform = `translate(${(e.clientX - r.left - r.width / 2) * 0.18}px, ${(e.clientY - r.top - r.height / 2) * 0.28}px)`;
    });
    b.addEventListener("pointerleave", () => (b.style.transform = ""));
  });
}

function tilt(sel) {
  if (!matchMedia("(pointer: fine)").matches) return;
  $$(sel).forEach((c) => {
    c.addEventListener("pointermove", (e) => {
      const r = c.getBoundingClientRect();
      const x = (e.clientX - r.left) / r.width - 0.5, y = (e.clientY - r.top) / r.height - 0.5;
      c.style.transform = `perspective(900px) rotateY(${x * 8}deg) rotateX(${-y * 8}deg) translateY(-4px)`;
    });
    c.addEventListener("pointerleave", () => (c.style.transform = ""));
  });
}

/* Typewriter that cycles through phrases, each tinted with a domain color */
function rotator(node, phrases) {
  if (!node) return;
  const word = node.querySelector(".word");
  let i = 0, j = 0, del = false;
  const reduced = matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduced) { word.textContent = phrases[0][0]; word.style.color = phrases[0][1]; return; }
  const tick = () => {
    const [txt, col] = phrases[i];
    word.style.color = col;
    j += del ? -1 : 1;
    word.textContent = txt.slice(0, j);
    let wait = del ? 28 : 55;
    if (!del && j === txt.length) { del = true; wait = 1900; }
    else if (del && j === 0) { del = false; i = (i + 1) % phrases.length; wait = 300; }
    setTimeout(tick, wait);
  };
  tick();
}

