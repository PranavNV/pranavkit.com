const fmtDate = (iso) => new Date(iso + "T12:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
const domTag = (k) => `<span class="tag" style="color:${DOMAINS[k].color}">${DOMAINS[k].short}</span>`;
const newsKind = (k) => `<span class="tag" style="color:${NEWS_KINDS[k].color}">${NEWS_KINDS[k].label}</span>`;

function pubHTML(p) {
  return `
    <article class="pub" style="--c:${DOMAINS[p.d[0]].color}">
      <span class="bar"></span>
      <div>
        <h4><a href="${p.u}" target="_blank" rel="noopener">${p.t}</a></h4>
        <div class="auth">${boldMe(p.a)}</div>
        <div class="venue">${p.v}</div>
        <div class="tags">${p.award ? `<span class="award-pill">★ ${p.award}</span>` : ""}${p.d.map(domTag).join("")}</div>
      </div>
      <div class="side">
        <a class="open" href="${p.u}" target="_blank" rel="noopener" aria-label="Open paper">${ARROW}</a>
      </div>
    </article>`;
}

/* ---------- News ---------- */
function renderNews(list, { limit = Infinity, filters } = {}) {
  let kind = null;
  const draw = () => {
    const items = NEWS.filter((n) => !kind || n.k === kind).slice(0, limit);
    list.innerHTML = items.map((n) => `
      <li class="news-item">
        <span class="when">${n.d}</span>
        <span>${newsKind(n.k)}</span>
        <span class="news-text">${n.h}</span>
      </li>`).join("");
    $$("a", list).forEach((a) => { a.target = "_blank"; a.rel = "noopener"; });
  };
  if (filters) {
    const all = [["all", "All", "var(--paper)"], ...Object.entries(NEWS_KINDS).map(([k, v]) => [k, v.label, v.color])];
    filters.innerHTML = all.map(([k, l, c]) => `<button class="chip ${k === "all" ? "on" : ""}" data-k="${k}"><i style="background:${c}"></i>${l}</button>`).join("");
    filters.addEventListener("click", (e) => {
      const b = e.target.closest(".chip");
      if (!b) return;
      kind = b.dataset.k === "all" ? null : b.dataset.k;
      $$(".chip", filters).forEach((c) => c.classList.toggle("on", c === b));
      draw();
    });
  }
  draw();
}

/* ---------- Publications ---------- */
function renderPublications(root) {
  const state = { q: "", dom: null, first: false, award: false };
  const tb = $(".toolbar", root);
  const out = $(".pub-out", root);
  const count = $(".result-count", root);

  const chips = $(".dom-chips", tb);
  chips.innerHTML = Object.entries(DOMAINS).map(([k, d]) => `<button class="chip" data-k="${k}"><i style="background:${d.color}"></i>${d.short}</button>`).join("");
  chips.addEventListener("click", (e) => {
    const b = e.target.closest(".chip");
    if (!b) return;
    state.dom = state.dom === b.dataset.k ? null : b.dataset.k;
    $$(".chip", chips).forEach((c) => c.classList.toggle("on", c.dataset.k === state.dom));
    draw();
  });
  $("input[type=search]", tb).addEventListener("input", (e) => { state.q = e.target.value.toLowerCase(); draw(); });
  $("#f-first", tb).addEventListener("change", (e) => { state.first = e.target.checked; draw(); });
  $("#f-award", tb).addEventListener("change", (e) => { state.award = e.target.checked; draw(); });

  const fromHash = () => {
    const hash = location.hash.match(/domain-(\w)/);
    if (!hash || !DOMAINS[hash[1]]) return false;
    state.dom = hash[1];
    $$(".chip", chips).forEach((c) => c.classList.toggle("on", c.dataset.k === state.dom));
    return true;
  };
  fromHash();
  addEventListener("hashchange", () => { if (fromHash()) { draw(); root.scrollIntoView({ behavior: "smooth" }); } });

  function draw() {
    const items = PUBLICATIONS.filter((p) =>
      (!state.dom || p.d.includes(state.dom)) &&
      (!state.first || p.first) &&
      (!state.award || p.award) &&
      (!state.q || (p.t + " " + p.a + " " + p.v).toLowerCase().includes(state.q)));
    count.textContent = `${items.length} of ${PUBLICATIONS.length}`;
    if (!items.length) { out.innerHTML = `<div class="empty">No papers match — try clearing a filter.</div>`; return; }
    const years = [...new Set(items.map((p) => p.y))].sort((a, b) => b - a);
    out.innerHTML = years.map((y) => `
      <div class="year-group">
        <div class="yr">${y}</div>
        <div>${items.filter((p) => p.y === y).map(pubHTML).join("")}</div>
      </div>`).join("");
  }
  draw();
}

